const asyncHandler = require('../utils/asyncHandler')
const { ok, created, okPaged } = require('../utils/response')
const { optPagination } = require('../utils/pagination')
const svc = require('../services/jobService')

exports.listForClient = asyncHandler(async (req, res) => okPaged(res, await svc.listForClient(req.params.clientId, req.query)))
exports.get = asyncHandler(async (req, res) => ok(res, await svc.getForClient(req.params.jobId, req.user)))
exports.create = asyncHandler(async (req, res) => created(res, await svc.create(req.user, req.body), 'Job created'))
exports.edit = asyncHandler(async (req, res) => ok(res, await svc.edit(req.params.jobId, req.body, req.user), 'Job updated'))
exports.publish = asyncHandler(async (req, res) => ok(res, await svc.publish(req.params.jobId, req.user), 'Job published'))
exports.remove = asyncHandler(async (req, res) => ok(res, await svc.remove(req.params.jobId, req.user), 'Job deleted'))
exports.cancel = asyncHandler(async (req, res) => ok(res, await svc.cancel(req.params.jobId, req.body.reason, req.user), 'Job cancelled'))
exports.listOpen = asyncHandler(async (req, res) => okPaged(res, await svc.listOpen(req.filters, optPagination(req.query))))
exports.getForFreelancer = asyncHandler(async (req, res) => ok(res, await svc.getForFreelancer(req.params.jobId, req.user)))

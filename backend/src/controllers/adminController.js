const asyncHandler = require('../utils/asyncHandler')
const { ok, okPaged } = require('../utils/response')
const admin = require('../services/adminService')
const issues = require('../services/issueService')

exports.dashboard = asyncHandler(async (_req, res) => ok(res, await admin.dashboard()))
exports.users = asyncHandler(async (req, res) => okPaged(res, await admin.listUsers(req.query)))
exports.user = asyncHandler(async (req, res) => ok(res, await admin.getUser(req.params.userId, req.user)))
exports.toggleStatus = asyncHandler(async (req, res) => ok(res, await admin.toggleStatus(req.user, req.params.userId), 'User status updated'))
exports.transactions = asyncHandler(async (req, res) => okPaged(res, await admin.transactions(req.query)))
exports.payment = asyncHandler(async (req, res) => ok(res, await admin.paymentDetails(req.params.paymentId, req.user)))
exports.contracts = asyncHandler(async (req, res) => okPaged(res, await admin.listContracts(req.query)))
exports.contract = asyncHandler(async (req, res) => ok(res, await admin.contractDetails(req.params.contractId)))
exports.reviews = asyncHandler(async (req, res) => okPaged(res, await admin.listReviews(req.query)))
exports.moderateReview = asyncHandler(async (req, res) => ok(res, await admin.moderateReview(req.user, req.params.reviewId, req.body.action), 'Review updated'))
exports.issues = asyncHandler(async (req, res) => okPaged(res, await issues.list(req.user, req.query)))
exports.resolveIssue = asyncHandler(async (req, res) => ok(res, await issues.resolve(req.user, req.params.issueId, req.body.resolution), 'Issue resolved'))
exports.actions = asyncHandler(async (req, res) => okPaged(res, await admin.actionsLog(req.query)))
exports.openJobs = asyncHandler(async (req, res) => okPaged(res, await admin.openJobs(req.query)))
exports.getProfile = asyncHandler(async (req, res) => ok(res, await admin.getProfile(req.params.adminId, req.user)))
exports.editProfile = asyncHandler(async (req, res) => ok(res, await admin.editProfile(req.params.adminId, req.user, req.body), 'Profile updated'))
